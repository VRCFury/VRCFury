        [TestCase(ValueType.Float, 3, true, ValueType.Float, 3, true, 1, 6, 6, 1)]
        public void CompressorCopiesTheClosestRepresentableValue(
            ValueType wireType,
            byte wireBits,
            bool wireFlipped,
            ValueType localType,
            byte localBits,
            bool localFlipped,
            float sendValue,
            float expectedCode,
            float receivedCode,
            float expectedValue
        ) {
            var root = new GameObject("Compressor");
            try {
                var avatar = root.AddComponent<VRCAvatarDescriptor>();
                avatar.baseAnimationLayers = Array.Empty<VRCAvatarDescriptor.CustomAnimLayer>();
                avatar.specialAnimationLayers = new[] {
                    new VRCAvatarDescriptor.CustomAnimLayer { type = VRCAvatarDescriptor.AnimLayerType.Action }
                };
                var injector = VRCFuryInjectorBuilder.GetInjector(avatar);
                var controllers = injector.GetService<ControllersService>();
                controllers.ClearCache(applyBaseMask: false);
                var action = controllers.GetAction();
                var local = new Parameter { name = "Input", valueType = localType, bitWidth = localBits, flippedRepresentation = localFlipped }.Synced();
                var wire = new Parameter { name = "Input", valueType = wireType, bitWidth = wireBits, flippedRepresentation = wireFlipped }.Synced();
                var parameters = injector.GetService<ExpressionParamsService>();
                parameters.AddOrMerge(local);
                var alignment = injector.GetService<ParameterPlatformAlignmentService>();
                var layout = new OptimizationDecision {
                    compress = new[] { wire },
                    boolSlots = wireType == ValueType.Bool ? 1 : 0,
                    numberSlots = wireType == ValueType.Bool ? 0 : 1
                };
                var data = alignment.CaptureDesktopData(layout, layout.compress);
                var mobile = parameters.GetSnapshot().ToList();
                var decision = ParameterPlatformAlignmentService.AlignForMobile(mobile, data).decision;
                parameters.SetParameters(mobile);
                injector.GetService<ParameterCompressorLayerService>().BuildLayer(decision, action);

                var slot = parameters.Single(p => p.name.Contains("_SyncData")).name;
                var states = action.GetLayers().SelectMany(layer => layer.allStates).ToArray();
                var send = states.Single(s => s.name.Contains("Send ") && s.name.Contains("Input"));
                var receive = states.Single(s => s.name.Contains("Receive") && s.name.Contains("Input"));
                // Start with a previous send at the other end of the slider, so the
                // rounding scratch still holds a large value when the next send begins.
                var values = new Dictionary<string, float> { ["Input"] = sendValue > 0.5f ? 0 : 1 };
                RunDrivers(send);
                values["Input"] = sendValue;
                RunDrivers(send);
                Assert.That(values[slot], Is.EqualTo(expectedCode), send.name);
                values[slot] = receivedCode;
                RunDrivers(receive);
                Assert.That(values["Input"], Is.EqualTo(expectedValue).Within(0.00001f), receive.name);

                void RunDrivers(VFState state) {
                    foreach (var op in state.behaviours.GetBehaviours<VRCAvatarParameterDriver>().SelectMany(d => d.parameters)) {
                        var v = op.type switch {
                            VRC.SDKBase.VRC_AvatarParameterDriver.ChangeType.Set => op.value,
                            VRC.SDKBase.VRC_AvatarParameterDriver.ChangeType.Copy => values[op.source],
                            _ => throw new InvalidOperationException($"Unexpected compressor driver operation {op.type}")
                        };
                        if (op.convertRange) v = Mathf.Lerp(op.destMin, op.destMax, Mathf.InverseLerp(op.sourceMin, op.sourceMax, v));
                        var declaration = parameters.FirstOrDefault(p => p.name == op.name);
                        var type = declaration?.valueType ?? (action.TryGetParam(op.name, out var p) && p.type == AnimatorControllerParameterType.Int
                            ? ValueType.Int : ValueType.Float);
                        // Simulate the small-write cutoff observed in the VRChat client.
                        if (type == ValueType.Float && values.TryGetValue(op.name, out var previous)
                            && Mathf.Approximately(previous, v)) continue;
                        values[op.name] = type == ValueType.Bool ? (v == 0 ? 0 : 1) : type == ValueType.Int ? (int)v : v;
                    }
                }
            } finally {
                UnityEngine.Object.DestroyImmediate(root);
            }
        }
    }
